// Wall metadata (public/wall/metadata.json) and the drawing palette → carving styles.

import type { CarveStyle } from "./carve/carve";
import look from "./look.json";

export interface WallMeta {
  width_mm: number;
  height_mm: number;
  detail_tile_mm: number;
  images: Record<string, { file: string; px?: [number, number]; rect_mm?: number[] }>;
  lighting: {
    default: {
      azimuth_deg: number;
      elevation_deg: number;
      sun_intensity: number;
      ambient_intensity: number;
      exposure: number;
      detail_strength: number;
    };
    sun_color: [number, number, number];
    sky_color: [number, number, number];
    ground_color: [number, number, number];
  };
  carving: CarveStyle & {
    drawing_width_mm: number;
    fresh_stone_lightening: number;
    demo_center_mm: [number, number];
  };
}

export const WALL_DIR = `${import.meta.env.BASE_URL}wall/`;

export async function loadMeta(): Promise<WallMeta> {
  const res = await fetch(WALL_DIR + "metadata.json");
  if (!res.ok) throw new Error(`metadata.json ${res.status}`);
  return res.json();
}

export interface PaletteColor {
  label: string;
  hex: string;
}

/**
 * Lab sliders (실험실). The carve keys set the brown carving; purple follows at fixed ratios
 * except for its depth. The look keys drive the wall shader directly.
 */
export interface LabSettings extends CarveStyle {
  /** 붓 거칠기: 0 = even round groove, 1 = default pecked brush */
  brush_roughness: number;
  purple_depth_ratio: number;
  /** 새김 어둡기: albedo inside the carving is multiplied by (1 − this) */
  carve_darkening: number;
  sun_intensity: number;
  /** −1 = cool (bluish), 0 = metadata sun_color, +1 = warm (low sun) */
  sun_warmth: number;
  ambient_intensity: number;
  exposure: number;
  detail_strength: number;
}

/** Keys that change the carve geometry (need a re-carve); the rest only change shading. */
export const CARVE_KEYS: (keyof LabSettings)[] = ["depth_mm", "bevel_sigma_mm", "peck_roughness", "purple_depth_ratio", "brush_roughness"];
/** Keys that change the drawing masks themselves (the strokes must be re-rasterized). */
export const RASTER_KEYS: (keyof LabSettings)[] = ["brush_roughness"];

/**
 * App defaults for the lab and the light, in the format "설정 복사" copies:
 * paste a copied JSON into src/look.json to change them. (metadata.json keeps the
 * baked wall's own record and is regenerated by tools/wall_bake/export.py.)
 */
export function defaultLab(): LabSettings {
  const { azimuth_deg: _az, elevation_deg: _el, ...lab } = look;
  return lab;
}

export const DEFAULT_LIGHT = { azimuth: look.azimuth_deg, elevation: look.elevation_deg };

/** Purple relative to brown: shallower, slightly crisper, less pecked (5 / 3.0 / 0.5 at the defaults). */
const PURPLE_RATIO = { depth_mm: 5 / 12, bevel_sigma_mm: 3.0 / 3.8, peck_roughness: 0.5 / 0.79 };

const WARM: [number, number, number] = [1.0, 0.72, 0.45];
const COOL: [number, number, number] = [0.72, 0.84, 1.0];

/** Sun color for a warmth in [−1, 1]; 0 returns `base` (metadata sun_color) unchanged. */
export function sunColor(base: [number, number, number], warmth: number): [number, number, number] {
  const t = Math.min(1, Math.abs(warmth)), to = warmth >= 0 ? WARM : COOL;
  return base.map((b, i) => b + (to[i] - b) * t) as [number, number, number];
}

export const PALETTE: PaletteColor[] = [
  { label: "갈색", hex: "#9d4a2c" },
  { label: "보라", hex: "#7c4c91" },
];

/** Brown = the main figures, deep 면새김; purple = a second group, shallower (as prototyped in the bake). */
export function carveStyles(lab: LabSettings): CarveStyle[] {
  return [
    { depth_mm: lab.depth_mm, bevel_sigma_mm: lab.bevel_sigma_mm, peck_roughness: lab.peck_roughness },
    {
      depth_mm: lab.depth_mm * lab.purple_depth_ratio,
      bevel_sigma_mm: lab.bevel_sigma_mm * PURPLE_RATIO.bevel_sigma_mm,
      peck_roughness: lab.peck_roughness * PURPLE_RATIO.peck_roughness,
    },
  ];
}

/** Carve layer resolution (WALL_ASSETS: about 1 mm/px). */
export const CARVE_MM_PER_PX = 1;
/** Brush diameter in mm: thick by default, like the book tracings. */
export const BRUSH_MM = { min: 8, max: 60, default: 22 };
/** Rubbing / tracing paper tone. */
export const PAPER_HEX = "#ece6dd";

export function hexToRgb(hex: string): [number, number, number] {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}
